test_that("a committed requirement is deprecated with a reason, and a draft is deleted", {
  con <- local_built_sample()
  expect_error(deprecate_requirement(con, "SYS-012", " "), "Say why")
  gone <- deprecate_requirement(con, "SYS-012", "Superseded")
  expect_identical(read_entity(con, "requirement", "SYS-012")$status, "deprecated")
  expect_match(DBI::dbGetQuery(con, "SELECT change_note FROM revision WHERE entity_id = 'SYS-012' ORDER BY rev DESC LIMIT 1")$change_note, "Superseded")
  # A failure it handled no longer counts as handled by it.
  delete_entity(con, "link", "L-0312")
  expect_true("FM-0001" %in% failure_findings(con)$subject_id[failure_findings(con)$rule == "handled_unlinked"])
  revert_change_set(con, gone$change_set, "engineer", "Undo")
  expect_identical(read_entity(con, "requirement", "SYS-012")$status, "committed")
  expect_error(delete_draft_requirement(con, "SYS-001"), "deprecated rather than deleted")
  draft <- DBI::dbGetQuery(con, "SELECT id FROM requirement WHERE status = 'draft' LIMIT 1")$id
  delete_draft_requirement(con, draft)
  expect_null(read_entity(con, "requirement", draft))
})

test_that("state machine events and variables can be edited without breaking what names them", {
  con <- local_built_sample()
  expect_error(rename_sm_event(con, "E-04", "gnss_gone"), "Assertion A-001 fires gnss_lost")
  expect_error(delete_sm_event(con, "E-04"), "Assertion A-001 fires gnss_lost")
  battery <- DBI::dbGetQuery(con, "SELECT id FROM sm_event WHERE name = 'battery_low'")$id
  expect_error(rename_sm_event(con, battery, "Battery Low"), "snake_case")
  expect_error(rename_sm_event(con, battery, "link_lost"), "already an event called link_lost")
  rename_sm_event(con, battery, "battery_critical")
  set_event_binding(con, battery, "IF-003", "soc")
  expect_identical(read_entity(con, "sm_event", battery)$field_name, "soc")
  expect_error(set_event_binding(con, battery, "IF-003", "nope"), "no field nope")
  set_event_binding(con, battery, "")
  expect_true(is.na(read_entity(con, "sm_event", battery)$interface_id))
  vars <- DBI::dbGetQuery(con, "SELECT id, name FROM sm_variable ORDER BY id")
  expect_error(delete_sm_variable(con, vars$id[vars$name == "gnss_valid"]), "uses gnss_valid")
  expect_error(update_sm_variable(con, vars$id[vars$name == "gnss_valid"], "initial_value", "maybe"), "true or false")
  update_sm_variable(con, vars$id[vars$name == "soc"], "unit", "%")
  expect_identical(read_entity(con, "sm_variable", vars$id[vars$name == "soc"])$unit, "%")
  rename_state_machine(con, "SM-001", "Flight modes v2")
  expect_identical(read_entity(con, "state_machine", "SM-001")$name, "Flight modes v2")
  events <- nrow(load_machine(con, "SM-001")$events)
  gone <- delete_entity(con, "state_machine", "SM-001")
  revert_change_set(con, gone$change_set, "engineer", "Undo")
  expect_identical(nrow(load_machine(con, "SM-001")$events), events)
})

test_that("a port's edits are checked against its connectors", {
  con <- local_built_sample()
  expect_error(save_port(con, "P-0003", "interface_id", "IF-002"), "connector K-0005 would no longer fit")
  expect_error(save_port(con, "P-0003", "direction", "out"), "would no longer fit")
  expect_error(save_port(con, "P-0003", "name", "nav_in"), "already has a port called nav_in")
  expect_identical(read_entity(con, "port", "P-0003")$interface_id, "IF-001")
  save_port(con, "P-0003", "name", "power_in")
  expect_identical(read_entity(con, "port", "P-0003")$name, "power_in")
  save_port(con, "P-0019", "interface_id", "")
  expect_true(is.na(read_entity(con, "port", "P-0019")$interface_id))
})

test_that("components move between levels and ungroup, and Undo reverses both", {
  con <- local_built_sample()
  expect_false("C-008" %in% move_targets(con, "C-004")$id)
  expect_error(move_element(con, "C-004", "C-008"), "isn't it or one of its own parts")
  moved <- move_element(con, "C-007", "C-004")
  expect_identical(read_entity(con, "element", "C-007")$parent_id, "C-004")
  revert_change_set(con, moved$change_set, "engineer", "Undo")
  expect_error(ungroup_element(con, "C-000"), "whole system")
  expect_error(ungroup_element(con, "C-001"), "no parts")
  done <- ungroup_element(con, "C-004")
  expect_null(read_entity(con, "element", "C-004"))
  expect_identical(read_entity(con, "element", "C-009")$parent_id, "C-000")
  revert_change_set(con, done$change_set, "engineer", "Undo")
  expect_identical(read_entity(con, "element", "C-009")$parent_id, "C-004")
})

test_that("property definitions are edited within their quantity, and deleted only when unused", {
  con <- local_built_sample()
  mass <- DBI::dbGetQuery(con, "SELECT id FROM property_def WHERE name = 'mass'")$id
  update_property_def(con, mass, "unit", "g")
  expect_identical(budget_status(con)$text[1], "3.31 / 3.60 kg")
  expect_error(update_property_def(con, mass, "unit", "W"), "measures mass")
  expect_error(update_property_def(con, mass, "rollup", "none"), "has a budget")
  expect_error(delete_property_def(con, mass), "held by 7 components")
  update_property_def(con, mass, "label", "Dry mass")
  expect_identical(read_entity(con, "property_def", mass)$name, "mass")
  supplier <- DBI::dbGetQuery(con, "SELECT id FROM property_def WHERE name = 'supplier'")$id
  delete_property_def(con, supplier)
  expect_null(read_entity(con, "property_def", supplier))
})
