test_that("the failure modes screen adds, edits, links and deletes", {
  state <- local_sample_state()
  shiny::testServer(mod_failures_server, args = list(state = state), {
    expect_match(as.character(output$list$html), "Response open (2)", fixed = TRUE)
    expect_match(as.character(output$checks$html), "Power loss not covered (3)", fixed = TRUE)
    session$setInputs(select = "FM-0001")
    html <- as.character(output$editor$html)
    expect_match(html, "Return to home on inertial navigation after 3 s", fixed = TRUE)
    expect_match(html, "Flight modes: Survey mission → gnss_lost → Return to home", fixed = TRUE)

    session$setInputs(add_new = list(value = "element|C-006", n = 1))
    id <- selected()
    expect_identical(read_entity(con(), "failure_mode", id)$cause_kind, "failed")
    session$setInputs(change = list(field = "system_effect", value = "Loss of lift", n = 2))
    expect_identical(read_entity(con(), "failure_mode", id)$system_effect, "Loss of lift")
    session$setInputs(change = list(field = "response_state", value = "accepted", n = 3))
    expect_identical(read_entity(con(), "failure_mode", id)$response_state, "placeholder")
    session$setInputs(link = list(type = "handled_by", value = "sm_transition|T-05", n = 4))
    expect_identical(failure_links(con(), id)$target_id, "T-05")
    session$setInputs(unlink = failure_links(con(), id)$id)
    expect_identical(nrow(failure_links(con(), id)), 0L)
    session$setInputs(delete = id)
    expect_null(read_entity(con(), "failure_mode", id))
    expect_null(selected())
  })
})

test_that("a check's suggestion adds the failure mode, and a reason sets a check aside", {
  state <- local_sample_state()
  shiny::testServer(mod_failures_server, args = list(state = state), {
    session$setInputs(add_suggested = list(subject = "interface|IF-002", cause = "out_of_range", field = "lat"))
    row <- read_entity(con(), "failure_mode", selected())
    expect_identical(c(row$subject_id, row$field_name, row$cause_kind), c("IF-002", "lat", "out_of_range"))
    session$setInputs(waive = list(rule = "missing_power_loss", kind = "port", id = "P-0016", note = "Each motor has its own fuse", n = 1))
    html <- as.character(output$checks$html)
    expect_match(html, "Set aside (1)", fixed = TRUE)
    expect_match(html, "Propulsion.pwr_in", fixed = TRUE)
    session$setInputs(unwaive = "missing_power_loss|port|P-0016")
    expect_no_match(as.character(output$checks$html), "Set aside (", fixed = TRUE)
  })
})
