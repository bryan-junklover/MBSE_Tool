test_that("the assertion builder writes the script and expectation core stores", {
  state <- local_sample_state()
  machine <- load_machine(shiny::isolate(state$con()), "SM-001")
  json <- assertion_json(machine, "S-MIS", "gnss_lost", "S-RTH", "5", event_default_sets(shiny::isolate(state$con()), "SM-001"))
  expect_identical(json$script, '[{"start":"S-MIS"},{"event":"gnss_lost","set":{"gnss_valid":false}}]')
  expect_identical(json$expect, '{"state":"S-RTH","within_s":5}')
  expect_identical(check_assertion(machine, jsonlite::fromJSON(json$script, simplifyVector = FALSE), jsonlite::fromJSON(json$expect))$result, "pass")
  expect_error(assertion_json(machine, "S-MIS", "gnss_lots", "S-RTH"), "isn't an event")
  expect_error(assertion_json(machine, "S-MIS", " ", "S-RTH"), "at least one event")
  expect_error(assertion_json(machine, "S-MIS", "gnss_lost", "S-RTH", "soon"), "number of seconds")
})

